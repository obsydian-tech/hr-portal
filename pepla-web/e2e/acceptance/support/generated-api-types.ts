import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * ONB-06.2: the one file the old text scans of pepla-web/src skip.
 *
 * REC-14 AC-7 (lock rec-14.4) requires the app's API types at src/app/core/api/openapi.d.ts, byte for
 * byte what openapi-typescript makes from api/openapi.yaml. That file describes every route, so it holds
 * other routes' words, headers and stage values, which the older scans ban in hand-written code. It is
 * skipped only at that exact path, and only while it still starts with the tool's banner; a hand-edited
 * copy anywhere else, or this file with the banner taken off, is scanned as before.
 *
 * A scan that needs the same skip wraps its file list: `withoutGeneratedApiTypes(files)`.
 */
export const GENERATED_API_TYPES = resolve(__dirname, '..', '..', '..', 'src', 'app', 'core', 'api', 'openapi.d.ts');
const BANNER = '/**\n * This file was auto-generated by openapi-typescript.\n';

export function isGeneratedApiTypes(file: string): boolean {
  return resolve(file) === GENERATED_API_TYPES && readFileSync(file, 'utf8').startsWith(BANNER);
}

export function withoutGeneratedApiTypes(files: string[]): string[] {
  return files.filter((f) => !isGeneratedApiTypes(f));
}
