// Writes src/app/ds/all.ts: every exported @Component and @Directive class in src/app/ds, for pages that
// show them all (the gallery, the parity check). Run after adding a component: node scripts/ds-all.mjs
import fs from 'fs';
import path from 'path';
const root = 'src/app/ds';
const skip = new Set(['PpFlags', 'PpRevealLog']);
const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (p.endsWith('.ts') && !p.endsWith('.spec.ts') && !/all\.ts$|index\.ts$|registry\.ts$/.test(p)) files.push(p); } };
walk(root);
const imports = [], names = [];
for (const f of files.sort()) {
  const src = fs.readFileSync(f, 'utf8');
  // A class counts when the last decorator before it, since the previous export, is @Component or @Directive with a selector.
  const real = [];
  let prev = 0;
  for (const m of src.matchAll(/export (abstract )?class (\w+)/g)) {
    const before = src.slice(prev, m.index);
    prev = m.index + m[0].length;
    if (m[1] || skip.has(m[2])) continue;
    if (/@(?:Component|Directive)\(\{[\s\S]*selector:/.test(before)) real.push(m[2]);
  }
  if (!real.length) continue;
  imports.push(`import { ${real.join(', ')} } from './${path.relative(root, f).replace(/\.ts$/, '').split(path.sep).join('/')}';`);
  names.push(...real);
}
fs.writeFileSync(path.join(root, 'all.ts'), `// GENERATED by scripts/ds-all.mjs. Every pp-* component and directive, for pages that show them all
// (the gallery, the parity check). Screens import only what they use.
${imports.join('\n')}

export const PP_ALL = [
${names.map((n) => `  ${n},`).join('\n')}
] as const;
`);
console.log(`${names.length} components and directives`);
