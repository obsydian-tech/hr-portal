#!/usr/bin/env node
// Writes src/app/ds/core/icon.registry.ts from the synced icon vocabulary
// (src/styles/design-system/icons.json). Only listed icons are imported, so the bundle carries
// only the icons Pepla uses. design-system:sync runs this; verify:design fails if it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('..', import.meta.url);
export const REGISTRY = fileURLToPath(new URL('src/app/ds/core/icon.registry.ts', ROOT));
const pascal = (n) => n.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');

export function render(icons = JSON.parse(readFileSync(new URL('src/styles/design-system/icons.json', ROOT), 'utf8')).icons) {
  const names = [...new Set(icons.map((i) => i.name))].sort();
  return [
    '// GENERATED by scripts/icon-registry.mjs from the synced icon vocabulary. Do not edit.',
    '// The only file in the app that imports Lucide. To add an icon, add it to the design system readme.',
    `import { ${names.map(pascal).join(', ')} } from 'lucide';`,
    '',
    'export type IconNode = readonly (readonly [string, Readonly<Record<string, string | number | undefined>>])[];',
    '',
    'export const ICONS = {',
    ...names.map((n) => `  '${n}': ${pascal(n)},`),
    '} as const satisfies Record<string, IconNode>;',
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(REGISTRY, render());
  console.log('src/app/ds/core/icon.registry.ts written');
}
