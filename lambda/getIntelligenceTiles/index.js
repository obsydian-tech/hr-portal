/**
 * Check if a rule should be visible to a given role
 */
function isRuleVisibleToRole(ruleId, role) {
  if (!role) return true; // No role filter = show all
  const config = RULE_CONFIG[ruleId];
  if (!config) return true; // Unknown rule = show to all
  return config.targetRoles.includes(role);
}

